export function getYahooSymbol(symbol) {
  const normalized = String(symbol || "BIST100").toUpperCase();
  const found = BIST_SYMBOLS.find((item) => item.symbol === normalized);
  return found?.yahoo || `${normalized}.IS`;
}

export function getSymbolMeta(symbol) {
  const normalized = String(symbol || "BIST100").toUpperCase();
  return BIST_SYMBOLS.find((item) => item.symbol === normalized) || { symbol: normalized, name: normalized };
}
